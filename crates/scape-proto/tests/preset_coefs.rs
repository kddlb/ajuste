fn check(name: &str, fixtures: &[&Fixture]) {
    let p = preset(name).unwrap();
    assert_eq!(p.points.len(), fixtures.len());
    for (point, fx) in p.points.iter().zip(fixtures) {
        for (rate, b, a) in fx.iter() {
            let c = design(point, *rate);
            for (got, want) in c.b.iter().chain(&c.a).zip(b.iter().chain(a)) {
                assert!(
                    (got - want).abs() < 2e-5,
                    "{name} {point:?} {rate:?}: got {:?}/{:?}, want {b:?}/{a:?}",
                    c.b,
                    c.a
                );
            }
        }
    }
}

#[test]
fn clarity_matches_bundle() {
    check("Clarity", &CLARITY);
}

#[test]
fn depth_matches_bundle() {
    check("Depth", &DEPTH);
}
